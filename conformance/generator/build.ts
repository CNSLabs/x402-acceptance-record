// Writes vectors/vectors.json, vectors/seeds.json and vectors/SHA256SUMS deterministically; --check compares bytes.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { V0, jcs, sha256hex, hex } from './util.ts';
import * as F from './fixtures.ts';
import { buildVectors } from './cases.ts';

const SPECIFICATION = {
  repository: 'https://github.com/CNSLabs/x402-acceptance-record',
  tag: 'draft-2026-10-21',
  commit: 'ad53b54ad59df93bd5d3258963f27acccdcec23c',
  files: {
    'SPEC.md': '82881ba0efdeb70fe64594f5af0c912ceb8e9190d7e91d5ed583335bf0176f4b',
    'CASES.md': '0a56953e55919a6b63a464359eb6050aee938c82c6585cb924cf415f3caba744',
  },
};

const seeds = {
  description: 'Seeds for every test key of the x402 acceptance record version 0 vectors. Ed25519 seeds: ks (seller, kid did:web:seller.example#ks), kb (buyer, kid cp-1), kx (never listed in trust.keys), ky (never listed in trust.issuers). secp256k1 private keys: buyer, other, seller. All throwaway, derived from labels, never funded on any chain. WALLET, PAYEE and ASSET are keccak-derived pseudo-addresses with no key.',
  derivation: 'seed(name) = sha256(utf8("x402-acceptance-record/v0 conformance seed: " + name)); pseudoAddress(label) = last 20 bytes of keccak256(utf8("x402-acceptance-record/v0 conformance address: " + label))',
  seeds: Object.fromEntries(F.SEED_NAMES.map((n) => [n, hex(F.SEED[n])])),
};

const vectors = buildVectors();
const perCase = new Map<string, number>();
for (const v of vectors) perCase.set(v.case, (perCase.get(v.case) ?? 0) + 1);

const doc = {
  profile: 'x402 acceptance record, version 0',
  specification: SPECIFICATION,
  generator: {
    seedsDigest: sha256hex(jcs(seeds.seeds)),
    note: 'Inputs are exact bytes as unpadded base64url; expectations are typed from CASES.md. Regenerates byte for byte with `npm run build`; `npm run check` verifies.',
    counts: { vectors: vectors.length, cases: perCase.size, perCase: Object.fromEntries(perCase) },
  },
  fixture: F.fixtureSummary(),
  vectors,
};

const vectorsText = JSON.stringify(doc, null, 2) + '\n';
const seedsText = JSON.stringify(seeds, null, 2) + '\n';
const sums = `${sha256hex(vectorsText)}  vectors.json\n${sha256hex(seedsText)}  seeds.json\n`;
const files: [string, string][] = [['vectors.json', vectorsText], ['seeds.json', seedsText], ['SHA256SUMS', sums]];

if (process.argv.includes('--check')) {
  let ok = true;
  for (const [name, content] of files) {
    const path = join(V0, 'vectors', name);
    if (!existsSync(path)) { console.error(`missing ${name}`); ok = false; continue; }
    if (readFileSync(path, 'utf8') !== content) { console.error(`${name} differs from the regenerated bytes`); ok = false; }
  }
  if (!ok) process.exit(1);
  console.log(`check ok: ${vectors.length} vectors regenerate byte for byte`);
} else {
  for (const [name, content] of files) writeFileSync(join(V0, 'vectors', name), content);
  for (const [c, n] of perCase) console.log(`${c}  ${n}`);
  console.log(`wrote ${vectors.length} vectors over ${perCase.size} cases; vectors.json sha256 ${sha256hex(vectorsText)}`);
}
